"""The gate's check job fails on agent attribution in a pull request's title, body, or own commits, with the line it found.

Each test runs the step's own script from gate.yml under the shell GitHub uses, in a real git repo, with a fake `gh` that answers through real `jq`.
"""

from __future__ import annotations

import json
import os
import subprocess
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parents[1]
GATE = ROOT / ".github" / "workflows" / "gate.yml"
FAKE_GH = """#!/usr/bin/env bash
[ -n "$GH_TOKEN" ] || exit 8
[ "$1 $2 $3" = "api repos/owner/repo/pulls/7 --jq" ] || exit 9
exec jq -r "$4" "$PR_JSON"
"""

TRAILER = "Co-authored-by: Claude <noreply@anthropic.com>"
ANTHROPIC_TRAILER = "co-authored-by: Some Model <noreply@anthropic.com>"
FOOTER = "\N{ROBOT FACE} Generated with [Claude Code](https://claude.com/claude-code)"
PLAIN_FOOTER = "Generated with Claude Code"
BY_FOOTER = "Generated by [Claude Code](https://claude.com/claude-code)"
SESSION = "https://claude.ai/code/session_01ABCdefGHI"
FOUND = [TRAILER, ANTHROPIC_TRAILER, FOOTER, PLAIN_FOOTER, BY_FOOTER, SESSION]


class Pr:
    def __init__(self, tmp_path: Path) -> None:
        self.tmp_path = tmp_path
        self.work = tmp_path / "work"
        self.work.mkdir()
        bin_dir = tmp_path / "bin"
        bin_dir.mkdir()
        gh = bin_dir / "gh"
        gh.write_text(FAKE_GH)
        gh.chmod(0o755)
        self.pr_json = tmp_path / "pr.json"
        self.env = {
            "PATH": f"{bin_dir}{os.pathsep}{os.environ['PATH']}",
            "HOME": str(tmp_path),
            "GIT_CONFIG_GLOBAL": os.devnull,
            "GIT_CONFIG_NOSYSTEM": "1",
            "GIT_AUTHOR_NAME": "Test",
            "GIT_AUTHOR_EMAIL": "test@example.com",
            "GIT_COMMITTER_NAME": "Test",
            "GIT_COMMITTER_EMAIL": "test@example.com",
            "GH_TOKEN": "fake-token",
            "REPO": "owner/repo",
            "PR_NUMBER": "7",
            "PR_JSON": str(self.pr_json),
        }
        self.git("init", "-q")
        self.commit(f"old commit on main\n\n{TRAILER}")
        self.base = self.git("rev-parse", "HEAD")

    def git(self, *args: str) -> str:
        return subprocess.run(["git", *args], cwd=self.work, env=self.env, check=True, capture_output=True, text=True).stdout.strip()

    def commit(self, message: str) -> str:
        self.git("commit", "-q", "--allow-empty", "-m", message)
        return self.git("rev-parse", "--short", "HEAD")

    def check(self, title: str = "fix: a clean title", body: str | None = "A clean body.") -> subprocess.CompletedProcess[str]:
        self.pr_json.write_text(json.dumps({"title": title, "body": body}))
        [step] = [s for s in yaml.safe_load(GATE.read_text())["jobs"]["check"]["steps"] if s.get("name") == "attribution"]
        env = {**self.env, "BASE_SHA": self.base, "HEAD_SHA": self.git("rev-parse", "HEAD")}
        return subprocess.run(["bash", "--noprofile", "--norc", "-eo", "pipefail", "-c", step["run"]], cwd=self.work, env=env, capture_output=True, text=True)


@pytest.fixture
def pr(tmp_path: Path) -> Pr:
    return Pr(tmp_path)


def test_a_clean_pull_request_passes_despite_old_trailers(pr: Pr) -> None:
    pr.commit("fix: clean")

    run = pr.check()

    assert run.returncode == 0, run.stdout
    assert run.stdout == ""


def test_a_pull_request_with_no_body_passes(pr: Pr) -> None:
    assert pr.check(body=None).returncode == 0


@pytest.mark.parametrize(
    "text",
    [
        "The Co-authored-by: Claude trailer is prose here.",
        "No claude.ai connectors, and see https://claude.ai/code for the product.",
        "Claude-Session: https://example.com",
        "Generated with care by Claude's reviewers.",
    ],
)
def test_prose_that_credits_no_agent_passes(pr: Pr, text: str) -> None:
    pr.commit(f"fix: clean\n\n{text}")

    run = pr.check(body=text)

    assert run.returncode == 0, run.stdout


@pytest.mark.parametrize("line", FOUND)
def test_the_body_fails_with_the_line_it_found(pr: Pr, line: str) -> None:
    run = pr.check(body=f"Summary\r\n\r\n{line}\r\n")

    assert run.returncode == 1
    assert f"Title or body: {line}\n" in run.stdout
    assert "Summary" not in run.stdout


@pytest.mark.parametrize("line", FOUND)
def test_the_title_fails_with_the_line_it_found(pr: Pr, line: str) -> None:
    run = pr.check(title=line)

    assert run.returncode == 1
    assert f"Title or body: {line}\n" in run.stdout


@pytest.mark.parametrize("line", FOUND)
def test_a_commit_fails_with_the_line_it_found(pr: Pr, line: str) -> None:
    sha = pr.commit(f"fix: one\n\n{line}")

    run = pr.check()

    assert run.returncode == 1
    assert f"Commit {sha} fix: one: {line}\n" in run.stdout


def test_each_commit_with_attribution_is_named_and_a_clean_one_is_not(pr: Pr) -> None:
    first = pr.commit(f"fix: one\n\n{TRAILER}")
    pr.commit("fix: two")
    third = pr.commit(f"fix: three\n\n{SESSION}")

    run = pr.check()

    assert run.returncode == 1
    assert f"{first} fix: one" in run.stdout
    assert f"{third} fix: three" in run.stdout
    assert "fix: two" not in run.stdout


def test_a_failure_says_how_to_clear_it(pr: Pr) -> None:
    run = pr.check(body=SESSION)

    assert "Reword the commits, edit the title or the body, then re-run this job." in run.stdout


def test_a_github_failure_fails_the_step(pr: Pr) -> None:
    pr.env["GH_TOKEN"] = ""

    run = pr.check()

    assert run.returncode != 0


def test_a_commit_range_git_cannot_read_fails_the_step(pr: Pr) -> None:
    pr.base = "0" * 40

    run = pr.check()

    assert run.returncode != 0


def test_a_crafted_body_is_never_run_as_code(pr: Pr, tmp_path: Path) -> None:
    marker = tmp_path / "ran"

    run = pr.check(body=f"$(touch {marker}) `touch {marker}` \"; touch {marker}\n{TRAILER} $(touch {marker})")

    assert run.returncode == 1
    assert not marker.exists()


def test_a_line_found_cannot_be_a_workflow_command(pr: Pr) -> None:
    run = pr.check(body=f"::error::{SESSION}")

    assert run.returncode == 1
    assert not any(line.lstrip().startswith("::") for line in run.stdout.splitlines())


def test_the_step_runs_in_the_required_check_job_before_the_check_command() -> None:
    steps = yaml.safe_load(GATE.read_text())["jobs"]["check"]["steps"]
    names = [s.get("name") for s in steps]
    commands = [i for i, s in enumerate(steps) if "COMMAND" in s.get("env", {})]

    assert names.index("attribution") < commands[0]
    assert "${{" not in steps[names.index("attribution")]["run"]
